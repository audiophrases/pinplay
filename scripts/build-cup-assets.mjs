// Builds PinPlay Cup runtime assets from the design packs.
//
//   node scripts/build-cup-assets.mjs "C:\Users\Admin\PinPlayCupMediaDesign"
//
// Writes cup/avatar-parts.js (all avatar parts inlined, one request) and copies
// chests, icons, logo, sounds and Lottie files into cup/. Prints the part counts
// that ARENA_AVATAR_PARTS in cloudflare/worker.js must match.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = process.argv[2];
if (!SRC) { console.error('usage: node scripts/build-cup-assets.mjs <PinPlayCupMediaDesign dir>'); process.exit(1); }
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'cup');

const PACK = path.join(SRC, 'PinPlay-Cup-Asset-Pack');
const SETS = [
  path.join(PACK, 'avatars'),
  path.join(SRC, 'PinPlay-Cup-Avatars-Expansion', 'fantasy'),
  path.join(SRC, 'PinPlay-Cup-Avatars-Expansion', 'music'),
  path.join(SRC, 'PinPlay-Cup-Avatars-Expansion', 'celebrities'),
];
// Recreates a copyrighted character's signature items (scar glasses, house scarf).
const EXCLUDE = new Set(['glasses-wizard-round-scar.svg', 'shirt-wizard-robe-scarf.svg']);

const inner = (file) => fs.readFileSync(file, 'utf8')
  .replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
const label = (stem) => stem.replace(/-/g, ' ');

const parts = { hair: [], eyes: [], mouth: [], glasses: [{ id: 'none' }], hat: [{ id: 'none' }], shirt: [] };
for (const dir of SETS) {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.svg') && !f.startsWith('base-') && !EXCLUDE.has(f)).sort();
  for (const f of files) {
    const m = f.match(/^(hair|eyes|mouth|glasses|hat|shirt)-(.+)\.svg$/);
    if (!m) continue;
    const [, cat, rest] = m;
    if (cat === 'hair') {
      const pair = rest.match(/^(.+)-(back|front)$/);
      const id = pair ? pair[1] : rest;
      let entry = parts.hair.find((h) => h.id === id);
      if (!entry) { entry = { id, name: label(id) }; parts.hair.push(entry); }
      entry[pair ? pair[2] : 'front'] = inner(path.join(dir, f));
    } else {
      parts[cat].push({ id: rest, name: label(rest), svg: inner(path.join(dir, f)) });
    }
  }
}
const base = Object.fromEntries(['neck', 'ears', 'head', 'cheeks']
  .map((k) => [k, inner(path.join(SETS[0], `base-${k}.svg`))]));

const skins = ['#F8D9C5', '#EDB78F', '#D79A67', '#B97753', '#89543E', '#583C35', '#E4D9DC', '#F3ECDC'];
const hairColors = ['#292D43', '#51372F', '#88553D', '#C57543', '#E3B961', '#E3C57D', '#CBD5E3', '#A888D8', '#E188AA', '#70BFA9', '#537ACE'];

const data = { viewBox: '0 -4 100 104', skins, hairColors, base, parts };
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'avatar-parts.js'),
  `// GENERATED by scripts/build-cup-assets.mjs — do not edit by hand.\n`
  + `window.CUP_AVATAR = ${JSON.stringify(data)};\n`);

const copy = (from, to) => { fs.mkdirSync(path.dirname(to), { recursive: true }); fs.copyFileSync(from, to); };
for (const sub of ['chests', 'icons', 'logo']) {
  for (const f of fs.readdirSync(path.join(PACK, 'game', sub))) copy(path.join(PACK, 'game', sub, f), path.join(OUT, sub, f));
}
for (const f of ['jackpot.json', 'podium.json', 'power-reveal.json']) copy(path.join(PACK, 'animations', f), path.join(OUT, 'fx', f));
copy(path.join(PACK, 'vendor', 'lottie.min.js'), path.join(OUT, 'fx', 'lottie.min.js'));
copy(path.join(PACK, 'vendor', 'LICENSE.txt'), path.join(OUT, 'fx', 'LICENSE-lottie.txt'));

const counts = {
  skin: skins.length, hair: parts.hair.length, hairColor: hairColors.length,
  eyes: parts.eyes.length, mouth: parts.mouth.length, glasses: parts.glasses.length,
  hat: parts.hat.length, shirt: parts.shirt.length,
};
console.log('avatar-parts.js', fs.statSync(path.join(OUT, 'avatar-parts.js')).size, 'bytes');
console.log('ARENA_AVATAR_PARTS =', JSON.stringify(counts).replace(/"/g, '').replace(/,/g, ', ').replace(/:/g, ': '));
